/** Контент продуктовых страниц (hero + секции ниже). */
export const productPages: ProductPageContent[] = productRoutes.map(
  (route, i) => {
    const extra = byHref[route.href];
    if (!extra) {
      throw new Error(`Missing product content for ${route.href}`);
    }

    return {
      href: route.href,
      title: route.title,
      description: route.description,
      index: String(i + 1).padStart(3, "0"),
      cover: covers[route.href] ?? "/covers/cat-kitchen.jpg",
      cta: {
        href: siteRoutes.contacts.href,
        label: "Обсудить проект",
      },
      ...extra,
    };
  },
);

export function getProductPage(href: string): ProductPageContent | undefined {
  return productPages.find((page) => page.href === href);
}
